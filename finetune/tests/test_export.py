"""Offline tests for the pure helpers in export_to_ollama.py (no downloads, no Ollama)."""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import export_to_ollama as ex  # noqa: E402
from common import chat_template  # noqa: E402


def test_plan_steps_per_mode():
    assert ex.plan_steps("adapter", False)[-3:] == ["quantize", "modelfile", "create"]
    assert "merge_gguf" in ex.plan_steps("adapter", False)
    assert "merge_gguf" not in ex.plan_steps("adapter", True)  # legacy ADAPTER keeps the LoRA separate
    assert "merge_hf" in ex.plan_steps("merge", False)
    assert ex.plan_steps("adapter", False, steps="create,modelfile") == ["modelfile", "create"]  # keeps order
    assert "setup" not in ex.plan_steps("merge", False, skip="setup")
    with pytest.raises(ValueError):
        ex.plan_steps("merge", False, steps="merge_gguf")


def test_export_paths():
    p = ex.export_paths("/x", "Q5_K_M")
    assert p["final"] == Path("/x/listsmart-writer-Q5_K_M.gguf")
    assert p["modelfile"] == Path("/x/Modelfile")


def test_resolve_tinker_path(tmp_path):
    assert ex.resolve_tinker_path(None, tmp_path) is None
    (tmp_path / "finetuned_model.txt").write_text("tinker://run/sampler_weights/a\n")
    assert ex.resolve_tinker_path(None, tmp_path) == "tinker://run/sampler_weights/a"
    # The downloadable external-weights save wins when train.py made one
    (tmp_path / "external_weights.txt").write_text("tinker://run/external_weights/a\n")
    assert ex.resolve_tinker_path(None, tmp_path) == "tinker://run/external_weights/a"
    assert ex.resolve_tinker_path("tinker://x", tmp_path) == "tinker://x"


def test_find_checkpoint_root(tmp_path):
    assert ex.find_checkpoint_root(tmp_path / "missing") == (None, None)
    lora = tmp_path / "a" / "nested"
    lora.mkdir(parents=True)
    (lora / "adapter_config.json").write_text("{}")
    assert ex.find_checkpoint_root(tmp_path / "a") == (None, None)  # weights file still missing
    (lora / "adapter_model.safetensors").write_bytes(b"")
    assert ex.find_checkpoint_root(tmp_path / "a") == ("lora", lora)

    full = tmp_path / "b"
    full.mkdir()
    (full / "config.json").write_text("{}")
    (full / "model-00001-of-00002.safetensors").write_bytes(b"")
    assert ex.find_checkpoint_root(full) == ("hf_model", full)


def test_safe_relative_path():
    assert ex.safe_relative_path("adapter/adapter_model.safetensors") == Path("adapter/adapter_model.safetensors")
    for bad in ("/etc/passwd", "../x", "a/../../x", ""):
        with pytest.raises(ValueError):
            ex.safe_relative_path(bad)


def test_parse_ollama_version_and_cutoff():
    assert ex.parse_ollama_version("ollama version is 0.34.4") == (0, 34, 4)
    assert ex.parse_ollama_version("Warning: client version is 0.34.4") == (0, 34, 4)
    assert ex.parse_ollama_version("nothing") is None
    assert (0, 34, 4) >= ex.OLLAMA_ADAPTERS_REMOVED > (0, 34, 0)


def test_parse_modelfile_from():
    text = "# Modelfile generated by \"ollama show\"\nFROM /Users/a/.ollama/models/blobs/sha256-abc\nTEMPLATE x\n"
    assert ex.parse_modelfile_from(text) == "/Users/a/.ollama/models/blobs/sha256-abc"
    assert ex.parse_modelfile_from("TEMPLATE x") is None


def test_render_modelfile_merged():
    text = ex.render_modelfile("./listsmart-writer-Q4_K_M.gguf", temperature=0.2, num_ctx=4096)
    assert "FROM ./listsmart-writer-Q4_K_M.gguf\n" in text
    assert "ADAPTER" not in text
    for stop in chat_template.STOP_STRINGS:
        assert f'PARAMETER stop "{stop}"' in text
    assert "PARAMETER temperature 0.2" in text and "PARAMETER num_ctx 4096" in text
    # The chat template ends the same way as the training prompt (thinking switched off)
    assert '<|im_start|>assistant\n<think>\n\n</think>\n\n"""' in text


def test_render_modelfile_legacy_adapter():
    text = ex.render_modelfile("qwen3:8b", adapter="./listsmart-lora-f16.gguf")
    assert "FROM qwen3:8b\nADAPTER ./listsmart-lora-f16.gguf\n" in text


def test_peak_disk():
    steps = ["base_gguf", "merge_gguf", "quantize"]
    assert ex.peak_disk_gb(steps) == round(8.7 + 16.4 + 5.0, 1)
    # With cleanup the base GGUF is gone before quantize writes its file
    assert ex.peak_disk_gb(steps, cleanup=True) == round(8.7 + 16.4, 1)
    assert ex.peak_disk_gb(steps, overrides={"base_gguf": 0.0}) == round(16.4 + 5.0, 1)
    assert ex.peak_disk_gb([]) == 0


def test_dry_run_changes_nothing(tmp_path, capsys):
    out = tmp_path / "export"
    ex.main(["--dry-run", "--export-dir", str(out), "--tinker-path", "tinker://run/sampler_weights/x"])
    printed = capsys.readouterr().out
    assert "DRY RUN" in printed and "ollama create listsmart-writer" in printed
    assert "llama-export-lora" in printed and "llama-quantize" in printed
    assert not out.exists()
